def train_mlp_2in(hidden, depth, fmt=DEFAULT_FMT, seeds=8, epochs=3000, n_side=64):
    """Train a 2-input MLP for f(x,y)=exp(x)-ln(y); best-of-seeds by grid max-err.

    Returns (layers, float_maxerr). Mirrors mlp/train_mlp.py (Adam + cosine LR,
    best-of-N), but with input dim 2 on a 2-D training grid over the same domains.
    """
    import numpy as np
    import torch
    import torch.nn as nn

    (xlo, xhi), (ylo, yhi) = X_DOMAIN, Y_DOMAIN
    gx = torch.linspace(xlo, xhi, n_side)
    gy = torch.linspace(ylo, yhi, n_side)
    XX, YY = torch.meshgrid(gx, gy, indexing="ij")
    inp = torch.stack([XX.reshape(-1), YY.reshape(-1)], dim=1)
    tgt = (torch.exp(inp[:, 0]) - torch.log(inp[:, 1])).unsqueeze(1)

    def build():
        layers = [nn.Linear(2, hidden), nn.ReLU()]
        for _ in range(depth - 1):
            layers += [nn.Linear(hidden, hidden), nn.ReLU()]
        layers += [nn.Linear(hidden, 1)]
        return nn.Sequential(*layers)

    best = None
    for seed in range(seeds):
        torch.manual_seed(seed)
        net = build()
        opt = torch.optim.Adam(net.parameters(), lr=5e-3)
        sched = torch.optim.lr_scheduler.CosineAnnealingLR(opt, epochs)
        lossf = nn.MSELoss()
        for _ in range(epochs):
            opt.zero_grad(); loss = lossf(net(inp), tgt); loss.backward()
            opt.step(); sched.step()
        with torch.no_grad():
            maxerr = (net(inp) - tgt).abs().max().item()
        if best is None or maxerr < best[0]:
            layers = [(m.weight.detach().numpy().astype(np.float64),
                       m.bias.detach().numpy().astype(np.float64))
                      for m in net if isinstance(m, nn.Linear)]
            best = (maxerr, layers)
    return best[1], best[0]


def mlp_2in_fp_maxerr(qm, npts=129):
    (xlo, xhi), (ylo, yhi) = X_DOMAIN, Y_DOMAIN
    import math
    worst = 0.0
    for i in range(npts):
        x = xlo + i * (xhi - xlo) / (npts - 1)
        xr = qm.fmt.quantize(x)
        for j in range(npts):
            y = ylo + j * (yhi - ylo) / (npts - 1)
            got = qm.fmt.dequantize(qm.forward_raw(xr, qm.fmt.quantize(y)))
            worst = max(worst, abs(got - (math.exp(x) - math.log(y))))
    return worst


def run_mlp_2in(hidden, depth, fmt=DEFAULT_FMT, do_synth=True):
    """Train, emit, bit-exact check, and synthesize a 2-input MLP cell."""
    from mlp.fixed_point_mlp import QuantMLP
    from mlp.verilog_gen_mlp import emit_verilog_mlp

    layers, fmaxerr = train_mlp_2in(hidden, depth, fmt)
    qm = QuantMLP(layers, fmt)
    name = f"mlp2_exp_ln_h{hidden}_d{depth}"
    emit_verilog_mlp(qm, name, RTL_DIR, inputs=("x_in", "y_in"), emit_tb=False)

    # bit-exact check on the stream wrapper (core_latency = #Linear layers)
    lat = len(qm.layers)
    emit_stream_wrapper_2in(name, fmt, RTL_DIR, core_latency=lat)
    raws = _sweep_raws(fmt)
    stream = f"{name}_stream"
    _emit_stream_tb(stream, fmt, raws)
    sim = os.path.join(RTL_DIR, f"{stream}_sim")
    subprocess.run(["iverilog", "-g2012", "-o", sim, f"{stream}.v", f"{stream}_tb.v",
                    f"{name}.v"], cwd=RTL_DIR, check=True)
    out = subprocess.run(["vvp", sim], cwd=RTL_DIR, check=True,
                         capture_output=True, text=True).stdout
    mm = n = 0
    for line in out.strip().splitlines():
        p = line.split(",")
        if len(p) != 3:
            continue
        n += 1
        if int(p[2]) != qm.forward_raw(int(p[0]), int(p[1])):
            mm += 1
    fpmax = mlp_2in_fp_maxerr(qm)
    print(f"{stream}: {n}/256 {'BIT-EXACT' if mm == 0 and n == 256 else f'{mm} mism'}, "
          f"fp max-err {fpmax:.4f} (float {fmaxerr:.4f})")
    res = {"name": name, "hidden": hidden, "depth": depth, "fp_maxerr": fpmax,
           "bit_exact": mm == 0 and n == 256}
    if do_synth:
        top = stream
        subprocess.run(["yosys", "-q", "-p",
                        f"synth_ice40 -top {top} -json {top}.json; stat",
                        f"{name}.v", f"{top}.v"], cwd=RTL_DIR, check=True,
                       capture_output=True, text=True, timeout=3600)
        pnr = subprocess.run(["nextpnr-ice40", *DEVICE, "--json", f"{top}.json",
                              "--freq", "12"], cwd=RTL_DIR, capture_output=True,
                             text=True, timeout=600)
        log = pnr.stdout + pnr.stderr
        res["lcs"] = _grep_int(r"ICESTORM_LC:\s*(\d+)/", log, default=None)
        res["fmax_mhz"] = (lambda m: round(float(m.group(1)), 1) if m else None)(
            re.search(r"Max frequency for clock '[^']*':\s*([\d.]+)\s*MHz", log))
        print(f"  PLACED: {res['lcs']} LC, {res['fmax_mhz']} MHz (UP5K sg48)")
    return res


def main():
    ap = argparse.ArgumentParser(description="Synthesis half of the 2-input arity experiment")
    ap.add_argument("--no-synth", action="store_true", help="emit + sim-check only")
    ap.add_argument("--mlp", action="store_true",
                    help="also train+synth 2-input MLP baselines (h8/h16 d1)")
    args = ap.parse_args()

    info = emit_symbolic_2in_verilog(out_dir=RTL_DIR)
    er = error_report()
    print(f"2-input symbolic unit exp(x)-ln(y) on x{X_DOMAIN} y{Y_DOMAIN}")
    print(f"  emitted: {os.path.relpath(info['rtl'])}")
    print(f"  fp max-err: {er['fp_maxerr']:.5f}  storage: {er['lut_entries']} entries")

    mm = sim_check()
    if mm:
        sys.exit(f"FAILED: {mm} mismatch(es) -- RTL diverges from the golden model")

    if not args.no_synth:
        r = synth()
        fits = {"hx1k": 1280, "up5k": 5280, "hx8k": 7680}
        smallest = next((d for d, c in fits.items() if r["lcs"] and r["lcs"] <= c), "none")
        print(f"  PLACED: {r['lcs']} LC, {r['ebr']} EBR, {r['fmax_mhz']} MHz "
              f"(UP5K sg48); smallest iCE40 = {smallest}")

    if args.mlp:
        print("\n2-input MLP baselines f(x,y)=exp(x)-ln(y):")
        for h, d in ((8, 1), (16, 1)):
            run_mlp_2in(h, d, do_synth=not args.no_synth)


if __name__ == "__main__":
    main()
