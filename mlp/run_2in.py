"""
Synthesis half of the arity experiment: drive the 2-input symbolic unit through
the SAME golden-model -> Icarus -> yosys/nextpnr pipeline as every other Track C
function unit, so its placed area is comparable to the single-input stream rows.

Steps (requires OSS CAD Suite: iverilog, yosys, nextpnr-ice40 on PATH):
  1. emit the combinational core (mlp/symbolic_2in.py) + a 2-input byte-serial
     stream wrapper (hardware/verilog_gen_stream.py::emit_stream_wrapper_2in);
  2. bit-exact check: feed a 256-point (x,y) sweep through Icarus and diff every
     output against hardware/fixed_point.py::FixedEML.eml_fix;
  3. synth: yosys synth_ice40 -> nextpnr-ice40 UP5K sg48 (19-pin wrapper), parse
     ICESTORM_LC / RAM / routed Fmax.

    python -m mlp.run_2in            # emit + sim-check + synth, print a result row
    python -m mlp.run_2in --no-synth # emit + sim-check only (no yosys/nextpnr)
"""

import argparse
import os
import re
import subprocess
import sys

from hardware.fixed_point import FixedEML
from hardware.verilog_gen_stream import emit_stream_wrapper_2in
from mlp.symbolic_2in import (DEFAULT_FMT, emit_symbolic_2in_verilog,
                              error_report, X_DOMAIN, Y_DOMAIN)

HERE = os.path.dirname(os.path.abspath(__file__))
RTL_DIR = os.path.join(os.path.dirname(HERE), "hardware", "rtl")
DEVICE = ("--up5k", "--package", "sg48")
CORE = "symbolic_exp_ln_2in"


def _sweep_raws(fmt, n=256):
    """Deterministic 256-point (x_raw, y_raw) sweep spanning both domains."""
    f6 = fmt.frac_bits - 6
    raws = []
    for i in range(n):
        x_raw = (i - 128) << f6                 # ~[-2, 2)
        y_raw = ((i >> 1) + 7) << f6            # ~[0.1, 10), strictly > 0
        raws.append((fmt.saturate(x_raw), fmt.saturate(y_raw)))
    return raws


def _emit_stream_tb(name, fmt, raws):
    """2-input stream tb: feed NIN bytes x then NIN bytes y per result, print CSV."""
    W = fmt.total_bits
    n = (W + 7) // 8
    wb = 8 * n
    lines = "\n".join(f"        xq[{i}]={x}; yq[{i}]={y};" for i, (x, y) in enumerate(raws))
    tb = f"""// Generated by mlp/run_2in.py -- 2-input stream bit-exact tb.
`timescale 1ns/1ps
module {name}_tb;
    localparam W = {W}, NIN = {n};
    reg clk = 0;
    always #5 clk = ~clk;
    reg [7:0] in_data = 0;
    reg in_valid = 0;
    wire [7:0] out_data;
    wire out_valid;
    {name} dut (.clk(clk), .in_data(in_data), .in_valid(in_valid),
                .out_data(out_data), .out_valid(out_valid));

    reg signed [W-1:0] xq [0:255];
    reg signed [W-1:0] yq [0:255];
    reg [{wb}-1:0] acc = 0;
    integer acc_n = 0, recv = 0;
    reg signed [W-1:0] yv;
    always @(posedge clk) begin
        #1;
        if (out_valid) begin
            acc = {{out_data, acc[{wb}-1:8]}};
            acc_n = acc_n + 1;
            if (acc_n == NIN) begin
                yv = acc[W-1:0];
                $display("%0d,%0d,%0d", xq[recv], yq[recv], yv);
                recv = recv + 1; acc_n = 0;
                if (recv == 256) $finish;
            end
        end
    end

    integer i, b;
    reg [{wb}-1:0] xext, yext;
    initial begin
{lines}
        for (i = 0; i < 256; i = i + 1) begin
            xext = {{{{({wb}-W){{xq[i][W-1]}}}}, xq[i]}};
            yext = {{{{({wb}-W){{yq[i][W-1]}}}}, yq[i]}};
            for (b = 0; b < NIN; b = b + 1) begin
                @(negedge clk); in_data = xext[8*b +: 8]; in_valid = 1;
            end
            for (b = 0; b < NIN; b = b + 1) begin
                @(negedge clk); in_data = yext[8*b +: 8]; in_valid = 1;
            end
        end
        @(negedge clk); in_valid = 0;
        repeat (400) @(posedge clk);
        $display("TIMEOUT: only %0d results", recv);
        $finish;
    end
endmodule
"""
    with open(os.path.join(RTL_DIR, f"{name}_tb.v"), "w") as f:
        f.write(tb)


def sim_check(fmt=DEFAULT_FMT) -> int:
    """Bit-exact: 256-point (x,y) sweep through Icarus vs FixedEML.eml_fix."""
    fe = FixedEML(fmt)
    raws = _sweep_raws(fmt)
    stream = f"{CORE}_stream"
    emit_stream_wrapper_2in(CORE, fmt, RTL_DIR)
    _emit_stream_tb(stream, fmt, raws)

    sim = os.path.join(RTL_DIR, f"{stream}_sim")
    subprocess.run(["iverilog", "-g2012", "-o", sim, f"{stream}.v", f"{stream}_tb.v",
                    f"{CORE}.v"], cwd=RTL_DIR, check=True)
    out = subprocess.run(["vvp", sim], cwd=RTL_DIR, check=True,
                         capture_output=True, text=True).stdout
    mismatches = n = 0
    for line in out.strip().splitlines():
        parts = line.split(",")
        if len(parts) != 3:
            continue
        x_raw, y_raw, y_rtl = int(parts[0]), int(parts[1]), int(parts[2])
        y_py = fe.eml_fix(x_raw, y_raw)
        n += 1
        if y_rtl != y_py:
            mismatches += 1
            if mismatches <= 5:
                print(f"  MISMATCH: x={x_raw} y={y_raw} rtl={y_rtl} py={y_py}")
    status = "BIT-EXACT" if mismatches == 0 and n == 256 else f"{mismatches} mismatch / {n} pts"
    print(f"{stream}: {n} points, {status}")
    return mismatches + (256 - n)


def _grep_int(pat, text, default=0):
    m = re.search(pat, text)
    return int(m.group(1)) if m else default


def synth(fmt=DEFAULT_FMT) -> dict:
    """yosys synth_ice40 -> nextpnr-ice40 UP5K sg48 on the 19-pin stream wrapper."""
    top = f"{CORE}_stream"
    subprocess.run(["yosys", "-q", "-p", f"synth_ice40 -top {top} -json {top}.json; stat",
                    f"{CORE}.v", f"{top}.v"], cwd=RTL_DIR, check=True,
                   capture_output=True, text=True, timeout=3600)
    pnr = subprocess.run(["nextpnr-ice40", *DEVICE, "--json", f"{top}.json", "--freq", "12"],
                         cwd=RTL_DIR, capture_output=True, text=True, timeout=600)
    log = pnr.stdout + pnr.stderr
    lcs = _grep_int(r"ICESTORM_LC:\s*(\d+)/", log, default=None)
    ebr = _grep_int(r"ICESTORM_RAM:\s*(\d+)/", log)
    fm = re.search(r"Max frequency for clock '[^']*':\s*([\d.]+)\s*MHz", log)
    fmax = round(float(fm.group(1)), 1) if fm else None
    return {"lcs": lcs, "ebr": ebr, "fmax_mhz": fmax}


